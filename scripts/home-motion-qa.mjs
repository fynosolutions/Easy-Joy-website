// Requires the local preview at 4173 and a dedicated browser CDP at 9334.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const out = fileURLToPath(new URL('../docs/redesign-qa/', import.meta.url));
const tab = await (await fetch('http://127.0.0.1:9334/json/new?about:blank', {method: 'PUT'})).json();
const ws = new WebSocket(tab.webSocketDebuggerUrl);
await new Promise((resolve, reject) => { ws.onopen = resolve; ws.onerror = reject; });
let id = 0;
const pending = new Map();
ws.onmessage = event => {
  const result = JSON.parse(event.data);
  if (!result.id) return;
  const callback = pending.get(result.id);
  pending.delete(result.id);
  result.error ? callback.reject(new Error(JSON.stringify(result.error))) : callback.resolve(result.result);
};
const send = (method, params = {}) => new Promise((resolve, reject) => { pending.set(++id, {resolve, reject}); ws.send(JSON.stringify({id, method, params})); });
const evaluate = async expression => {
  const value = await send('Runtime.evaluate', {expression, returnByValue: true, awaitPromise: true});
  if (value.exceptionDetails) throw new Error(JSON.stringify(value.exceptionDetails));
  return value.result.value;
};
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const resize = (width,height=900) => send('Emulation.setDeviceMetricsOverride', {width, height, deviceScaleFactor: 1, mobile: false});
const go = async () => { await send('Page.navigate', {url: 'http://127.0.0.1:4173/'}); await pause(650); await evaluate('document.fonts.ready'); };
const scroll = async selector => { await evaluate(`document.querySelector('${selector}').scrollIntoView({behavior:'instant'})`); await pause(850); };
const shot = async name => { const image = await send('Page.captureScreenshot', {format: 'png'}); await fs.writeFile(out + name + '.png', Buffer.from(image.data, 'base64')); };
const report = {};
try {
  await resize(1440); await go(); await shot('editorial-hero-desktop');
  await scroll('#brand-intro'); await shot('editorial-brand-desktop');
  const animationBefore = await evaluate("getComputedStyle(document.querySelector('.marquee-track')).transform");
  await pause(250);
  assert.notEqual(await evaluate("getComputedStyle(document.querySelector('.marquee-track')).transform"), animationBefore);
  await evaluate("document.querySelector('.motion-toggle').click()");
  assert.equal(await evaluate("getComputedStyle(document.querySelector('.marquee-track')).animationPlayState"), 'paused');
  await evaluate("document.querySelector('.motion-toggle').click()");
  await scroll('#menu-highlights'); await shot('editorial-menu-desktop');
  await evaluate("document.querySelector('[data-carousel-step=\"1\"]').click()"); await pause(700);
  assert.ok(await evaluate("document.querySelector('.signature-carousel').scrollLeft > 100"));
  await evaluate("document.querySelector('.signature-carousel').focus()");
  await send('Input.dispatchKeyEvent', {type: 'keyDown', key: 'Home', code: 'Home'}); await pause(700);
  assert.ok(await evaluate("document.querySelector('.signature-carousel').scrollLeft < 3"));
  await evaluate("document.activeElement.blur()");
  const autoBefore = await evaluate("document.querySelector('.signature-carousel').scrollLeft");
  await pause(5800);
  assert.ok(await evaluate("document.querySelector('.signature-carousel').scrollLeft") > autoBefore + 50, 'Visible carousel should advance');
  await evaluate("document.querySelector('.motion-toggle').click()");
  await pause(700);
  const pausedAt = await evaluate("document.querySelector('.signature-carousel').scrollLeft");
  await pause(5300);
  assert.equal(await evaluate("document.querySelector('.signature-carousel').scrollLeft"), pausedAt, 'Paused carousel moved');
  await evaluate("document.querySelector('.motion-toggle').click()");
  await scroll('#hot-pot'); await shot('editorial-hotpot-desktop');
  await evaluate('scrollBy({top:220,behavior:"instant"})'); await pause(250);
  const sticky = await evaluate("({top:document.querySelector('#hot-pot').getBoundingClientRect().top,header:document.querySelector('.site-header').getBoundingClientRect().height,transform:document.querySelector('#hot-pot .scene-visual').style.transform})");
  assert.ok(Math.abs(sticky.top - sticky.header) < 2, JSON.stringify(sticky));
  assert.ok(sticky.transform.includes('translate3d'));
  await scroll('#dim-sum'); await shot('editorial-dimsum-desktop');
  await scroll('#dining-experience'); await shot('editorial-dining-desktop');
  await scroll('#at-the-table'); await shot('editorial-atmosphere-desktop');
  await scroll('#guest-reviews'); await shot('editorial-reviews-desktop');
  await resize(390); await go(); await shot('editorial-hero-mobile');
  await scroll('#menu-highlights'); await shot('editorial-menu-mobile');
  await scroll('#hot-pot'); await shot('editorial-hotpot-mobile');
  assert.equal(await evaluate("getComputedStyle(document.querySelector('#hot-pot')).position"), 'relative');
  assert.ok(await evaluate('document.documentElement.scrollWidth <= innerWidth'));
  await resize(1440,768); await go();
  assert.equal(await evaluate("getComputedStyle(document.querySelector('#hot-pot')).position"), 'relative');
  assert.ok(await evaluate("document.querySelector('#hot-pot .scene-panel').scrollHeight <= document.querySelector('#hot-pot').clientHeight+1"));
  await resize(1440);
  await send('Emulation.setEmulatedMedia', {features: [{name: 'prefers-reduced-motion', value: 'reduce'}]}); await go();
  assert.equal(await evaluate("getComputedStyle(document.querySelector('.marquee-track')).animationName"), 'none');
  assert.equal(await evaluate("getComputedStyle(document.querySelector('#hot-pot')).position"), 'relative');
  assert.equal(await evaluate("document.querySelector('.motion-toggle').disabled"), true);
  await send('Emulation.setScriptExecutionDisabled', {value: true}); await go();
  assert.equal(await evaluate("document.querySelectorAll('.signature-slide').length"), 6);
  assert.equal(await evaluate("document.querySelector('.carousel-controls').hidden"), true);
  await scroll('#menu-highlights');
  await evaluate("document.querySelector('.signature-carousel').scrollLeft=400");
  assert.ok(await evaluate("document.querySelector('.signature-carousel').scrollLeft > 100"));
  report.passed = true;
  report.checks = ['moving marquee and pause', 'carousel buttons and keyboard', 'visible autoplay', 'pause stops autoplay', 'desktop sticky chapters and parallax', 'mobile natural flow', 'reduced motion', 'no-JS content and horizontal scroll'];
  report.sticky = sticky;
  await fs.writeFile(out + 'home-motion-results.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally {
  ws.close();
  await fetch('http://127.0.0.1:9334/json/close/' + tab.id);
}
